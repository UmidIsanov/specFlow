/** Системы объекта в том порядке, в каком их перечисляют в проекте. */
export const SYSTEMS = ["ПС", "СОУЭ", "СКС", "СОТ", "СКУД", "АПТ", "ПЕРИМЕТР"] as const;

/** Расшифровка одной строкой — для select, заголовков и мест, где попап не покажешь. */
export function abbrLabel(term: string): string {
  const entry = ABBR[term.toUpperCase()];
  return entry ? `${term} — ${entry.full.toLowerCase()}` : term;
}

// длинные вперёд, иначе «СКС» перебьёт «СКУД» на общем начале
const TERMS = Object.keys(ABBR).sort((a, b) => b.length - a.length);
const LETTER = /[A-Za-zА-Яа-яЁё0-9]/;

/** Режет текст на куски: строка — обычный текст, объект — найденное сокращение. */
export function splitByAbbr(text: string): (string | { term: string })[] {
  const out: (string | { term: string })[] = [];
  let plain = "";
  let i = 0;

  scan: while (i < text.length) {
    for (const term of TERMS) {
      if (!text.startsWith(term, i)) continue;
      // «ПС» внутри «АПС» или «СОТ» внутри «СОТРУДНИК» — часть слова, а не сокращение
      const before = text[i - 1];
      const after = text[i + term.length];
      if ((before && LETTER.test(before)) || (after && LETTER.test(after))) continue;
      if (plain) {
        out.push(plain);
        plain = "";
      }
      out.push({ term });
      i += term.length;
      continue scan;
    }
    plain += text[i++];
  }

  if (plain) out.push(plain);
  return out;
}
